-- Run once in each airport database after taking a database backup.
-- This permanently deletes the values in these columns from all three tables.
SET XACT_ABORT ON;

BEGIN TRY
  BEGIN TRANSACTION;

  IF COL_LENGTH('dbo.ERRORTICKETING', 'VOIDED_AT') IS NOT NULL
    ALTER TABLE dbo.ERRORTICKETING DROP COLUMN VOIDED_AT;
  IF COL_LENGTH('dbo.ERRORTICKETING', 'VOID_REASON') IS NOT NULL
    ALTER TABLE dbo.ERRORTICKETING DROP COLUMN VOID_REASON;
  IF COL_LENGTH('dbo.ERRORTICKETING', 'RESTORED_AT') IS NOT NULL
    ALTER TABLE dbo.ERRORTICKETING DROP COLUMN RESTORED_AT;
  IF COL_LENGTH('dbo.ERRORTICKETING', 'RESTORED_BY') IS NOT NULL
    ALTER TABLE dbo.ERRORTICKETING DROP COLUMN RESTORED_BY;

  IF COL_LENGTH('dbo.G_ERRORTICKETING', 'VOIDED_AT') IS NOT NULL
    ALTER TABLE dbo.G_ERRORTICKETING DROP COLUMN VOIDED_AT;
  IF COL_LENGTH('dbo.G_ERRORTICKETING', 'VOID_REASON') IS NOT NULL
    ALTER TABLE dbo.G_ERRORTICKETING DROP COLUMN VOID_REASON;
  IF COL_LENGTH('dbo.G_ERRORTICKETING', 'RESTORED_AT') IS NOT NULL
    ALTER TABLE dbo.G_ERRORTICKETING DROP COLUMN RESTORED_AT;
  IF COL_LENGTH('dbo.G_ERRORTICKETING', 'RESTORED_BY') IS NOT NULL
    ALTER TABLE dbo.G_ERRORTICKETING DROP COLUMN RESTORED_BY;

  IF COL_LENGTH('dbo.P_ERRORTICKETING', 'VOIDED_AT') IS NOT NULL
    ALTER TABLE dbo.P_ERRORTICKETING DROP COLUMN VOIDED_AT;
  IF COL_LENGTH('dbo.P_ERRORTICKETING', 'VOID_REASON') IS NOT NULL
    ALTER TABLE dbo.P_ERRORTICKETING DROP COLUMN VOID_REASON;
  IF COL_LENGTH('dbo.P_ERRORTICKETING', 'RESTORED_AT') IS NOT NULL
    ALTER TABLE dbo.P_ERRORTICKETING DROP COLUMN RESTORED_AT;
  IF COL_LENGTH('dbo.P_ERRORTICKETING', 'RESTORED_BY') IS NOT NULL
    ALTER TABLE dbo.P_ERRORTICKETING DROP COLUMN RESTORED_BY;

  COMMIT TRANSACTION;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
  THROW;
END CATCH;
