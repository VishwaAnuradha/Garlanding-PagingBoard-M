-- =========================================================================================
-- Fix ID = 0 on TICKETING_G, TICKETING_P, and TICKETING_C across all databases
-- Ensures ID always strictly matches SERIALNO (ID = 1, 2, 3...)
-- =========================================================================================

-- 1. Fix dbo.TICKETING_G
IF EXISTS (SELECT 1 FROM dbo.TICKETING_G WHERE ID = 0)
BEGIN
  SET IDENTITY_INSERT dbo.TICKETING_G ON;
  
  INSERT INTO dbo.TICKETING_G (ID, SERIALNO, F_NO, COMPANY, TICKET_TYPE_ID, QTY, CHARGE, USERID, SESSIONENDFLAG, DATETIME, SessionId, CREDIT)
  SELECT 
    CASE WHEN SERIALNO > 0 THEN SERIALNO ELSE 1 END,
    CASE WHEN SERIALNO > 0 THEN SERIALNO ELSE 1 END,
    F_NO, COMPANY, TICKET_TYPE_ID, QTY, CHARGE, USERID, SESSIONENDFLAG, DATETIME, SessionId, CREDIT
  FROM dbo.TICKETING_G 
  WHERE ID = 0;

  DELETE FROM dbo.TICKETING_G WHERE ID = 0;

  SET IDENTITY_INSERT dbo.TICKETING_G OFF;
END;

-- 2. Fix dbo.TICKETING_P
IF EXISTS (SELECT 1 FROM dbo.TICKETING_P WHERE ID = 0)
BEGIN
  SET IDENTITY_INSERT dbo.TICKETING_P ON;

  INSERT INTO dbo.TICKETING_P (ID, SERIALNO, F_NO, COMPANY, TICKET_TYPE_ID, QTY, CHARGE, USERID, SESSIONENDFLAG, DATETIME, verified, SessionId, CREDIT)
  SELECT 
    CASE WHEN SERIALNO > 0 THEN SERIALNO ELSE 1 END,
    CASE WHEN SERIALNO > 0 THEN SERIALNO ELSE 1 END,
    F_NO, COMPANY, TICKET_TYPE_ID, QTY, CHARGE, USERID, SESSIONENDFLAG, DATETIME, verified, SessionId, CREDIT
  FROM dbo.TICKETING_P 
  WHERE ID = 0;

  DELETE FROM dbo.TICKETING_P WHERE ID = 0;

  SET IDENTITY_INSERT dbo.TICKETING_P OFF;
END;

-- 3. Fix RECEIPT_NO in dbo.TICKETING_C where RECEIPT_NO is 0
UPDATE dbo.TICKETING_C 
SET RECEIPT_NO = 1 
WHERE (RECEIPT_NO = 0 OR RECEIPT_NO IS NULL) AND SERIALNO = 1;

-- Also fix any RECEIPT_NO = 0 where SERIALNO > 1 by matching sub-tables
UPDATE c
SET c.RECEIPT_NO = g.ID
FROM dbo.TICKETING_C c
INNER JOIN dbo.TICKETING_G g ON g.SERIALNO = c.SERIALNO AND c.TICKET_TYPE_ID = 1
WHERE c.RECEIPT_NO = 0 OR c.RECEIPT_NO IS NULL;

UPDATE c
SET c.RECEIPT_NO = p.ID
FROM dbo.TICKETING_C c
INNER JOIN dbo.TICKETING_P p ON p.F_NO = c.F_NO AND c.TICKET_TYPE_ID IN (2, 3)
WHERE c.RECEIPT_NO = 0 OR c.RECEIPT_NO IS NULL;

-- 4. Reseed identity seeds to the current MAX(ID) so subsequent inserts naturally increment
DECLARE @MaxG INT = ISNULL((SELECT MAX(ID) FROM dbo.TICKETING_G), 0);
IF @MaxG > 0 DBCC CHECKIDENT ('dbo.TICKETING_G', RESEED, @MaxG);

DECLARE @MaxP INT = ISNULL((SELECT MAX(ID) FROM dbo.TICKETING_P), 0);
IF @MaxP > 0 DBCC CHECKIDENT ('dbo.TICKETING_P', RESEED, @MaxP);

SELECT 'TICKETING_G' AS [Table], ID, SERIALNO, CHARGE, F_NO FROM dbo.TICKETING_G ORDER BY ID;
SELECT 'TICKETING_P' AS [Table], ID, SERIALNO, CHARGE, F_NO FROM dbo.TICKETING_P ORDER BY ID;
SELECT 'TICKETING_C' AS [Table], ID, SERIALNO, RECEIPT_NO, TICKET_TYPE_ID, CHARGE FROM dbo.TICKETING_C ORDER BY ID;

