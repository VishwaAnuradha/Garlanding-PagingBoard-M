-- Run once in each airport database.
-- Creates the type-specific error-ticket tables and copies existing shared
-- error-ticket rows without recreating the removed tracking columns.
SET XACT_ABORT ON;

IF OBJECT_ID('dbo.ERRORTICKETING', 'U') IS NULL
  THROW 50001, 'dbo.ERRORTICKETING must exist before creating the type-specific error-ticket tables.', 1;

IF COL_LENGTH('dbo.ERRORTICKETING', 'SessionId') IS NULL
  ALTER TABLE dbo.ERRORTICKETING ADD SessionId INT NULL;
IF COL_LENGTH('dbo.ERRORTICKETING', 'CREDIT') IS NULL
  ALTER TABLE dbo.ERRORTICKETING ADD CREDIT INT NULL;
GO

IF OBJECT_ID('dbo.G_ERRORTICKETING', 'U') IS NULL
BEGIN
  IF COL_LENGTH('dbo.ERRORTICKETING', 'RECEIPT_NO') IS NOT NULL
    SELECT TOP (0) ID, SERIALNO, TICKET_TYPE_ID, USERID, SESSIONENDFLAG, DATETIME,
                   CHARGE, QTY, F_NO, COMPANY, RECEIPT_NO, SessionId, CREDIT
    INTO dbo.G_ERRORTICKETING
    FROM dbo.ERRORTICKETING;
  ELSE
    SELECT TOP (0) ID, SERIALNO, TICKET_TYPE_ID, USERID, SESSIONENDFLAG, DATETIME,
                   CHARGE, QTY, F_NO, COMPANY, SessionId, CREDIT
    INTO dbo.G_ERRORTICKETING
    FROM dbo.ERRORTICKETING;
END;
GO

IF OBJECT_ID('dbo.P_ERRORTICKETING', 'U') IS NULL
BEGIN
  IF COL_LENGTH('dbo.ERRORTICKETING', 'RECEIPT_NO') IS NOT NULL
    SELECT TOP (0) ID, SERIALNO, TICKET_TYPE_ID, USERID, SESSIONENDFLAG, DATETIME,
                   CHARGE, QTY, F_NO, COMPANY, RECEIPT_NO, SessionId, CREDIT
    INTO dbo.P_ERRORTICKETING
    FROM dbo.ERRORTICKETING;
  ELSE
    SELECT TOP (0) ID, SERIALNO, TICKET_TYPE_ID, USERID, SESSIONENDFLAG, DATETIME,
                   CHARGE, QTY, F_NO, COMPANY, SessionId, CREDIT
    INTO dbo.P_ERRORTICKETING
    FROM dbo.ERRORTICKETING;
END;
GO

IF COL_LENGTH('dbo.G_ERRORTICKETING', 'SessionId') IS NULL
  ALTER TABLE dbo.G_ERRORTICKETING ADD SessionId INT NULL;
IF COL_LENGTH('dbo.G_ERRORTICKETING', 'CREDIT') IS NULL
  ALTER TABLE dbo.G_ERRORTICKETING ADD CREDIT INT NULL;
IF COL_LENGTH('dbo.P_ERRORTICKETING', 'SessionId') IS NULL
  ALTER TABLE dbo.P_ERRORTICKETING ADD SessionId INT NULL;
IF COL_LENGTH('dbo.P_ERRORTICKETING', 'CREDIT') IS NULL
  ALTER TABLE dbo.P_ERRORTICKETING ADD CREDIT INT NULL;
GO

SET XACT_ABORT ON;
BEGIN TRY
  BEGIN TRANSACTION;

  IF COL_LENGTH('dbo.ERRORTICKETING', 'RECEIPT_NO') IS NOT NULL
  BEGIN
    INSERT INTO dbo.G_ERRORTICKETING
      (ID, SERIALNO, TICKET_TYPE_ID, USERID, SESSIONENDFLAG, DATETIME, CHARGE, QTY,
       F_NO, COMPANY, RECEIPT_NO, SessionId, CREDIT)
    SELECT source.ID, source.SERIALNO, source.TICKET_TYPE_ID, source.USERID, source.SESSIONENDFLAG,
           source.DATETIME, source.CHARGE, source.QTY, source.F_NO, source.COMPANY,
           source.RECEIPT_NO, source.SessionId, ISNULL(source.CREDIT, 0)
    FROM dbo.ERRORTICKETING AS source
    WHERE source.TICKET_TYPE_ID = 1
      AND NOT EXISTS (SELECT 1 FROM dbo.G_ERRORTICKETING AS target WHERE target.ID = source.ID);

    INSERT INTO dbo.P_ERRORTICKETING
      (ID, SERIALNO, TICKET_TYPE_ID, USERID, SESSIONENDFLAG, DATETIME, CHARGE, QTY,
       F_NO, COMPANY, RECEIPT_NO, SessionId, CREDIT)
    SELECT source.ID, source.SERIALNO, source.TICKET_TYPE_ID, source.USERID, source.SESSIONENDFLAG,
           source.DATETIME, source.CHARGE, source.QTY, source.F_NO, source.COMPANY,
           source.RECEIPT_NO, source.SessionId, ISNULL(source.CREDIT, 0)
    FROM dbo.ERRORTICKETING AS source
    WHERE source.TICKET_TYPE_ID IN (2, 3)
      AND NOT EXISTS (SELECT 1 FROM dbo.P_ERRORTICKETING AS target WHERE target.ID = source.ID);
  END
  ELSE
  BEGIN
    INSERT INTO dbo.G_ERRORTICKETING
      (ID, SERIALNO, TICKET_TYPE_ID, USERID, SESSIONENDFLAG, DATETIME, CHARGE, QTY,
       F_NO, COMPANY, SessionId, CREDIT)
    SELECT source.ID, source.SERIALNO, source.TICKET_TYPE_ID, source.USERID, source.SESSIONENDFLAG,
           source.DATETIME, source.CHARGE, source.QTY, source.F_NO, source.COMPANY,
           source.SessionId, ISNULL(source.CREDIT, 0)
    FROM dbo.ERRORTICKETING AS source
    WHERE source.TICKET_TYPE_ID = 1
      AND NOT EXISTS (SELECT 1 FROM dbo.G_ERRORTICKETING AS target WHERE target.ID = source.ID);

    INSERT INTO dbo.P_ERRORTICKETING
      (ID, SERIALNO, TICKET_TYPE_ID, USERID, SESSIONENDFLAG, DATETIME, CHARGE, QTY,
       F_NO, COMPANY, SessionId, CREDIT)
    SELECT source.ID, source.SERIALNO, source.TICKET_TYPE_ID, source.USERID, source.SESSIONENDFLAG,
           source.DATETIME, source.CHARGE, source.QTY, source.F_NO, source.COMPANY,
           source.SessionId, ISNULL(source.CREDIT, 0)
    FROM dbo.ERRORTICKETING AS source
    WHERE source.TICKET_TYPE_ID IN (2, 3)
      AND NOT EXISTS (SELECT 1 FROM dbo.P_ERRORTICKETING AS target WHERE target.ID = source.ID);
  END;

  COMMIT TRANSACTION;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
  THROW;
END CATCH;
GO
